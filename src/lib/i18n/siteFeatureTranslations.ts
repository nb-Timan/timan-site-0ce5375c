export const SITE_FEATURE_TRANSLATIONS: Record<PortalUiLanguage, Dict> = {
  da,
  en,
  de,
  it,
  hu,
  sv,
  fr,
  pl,
  cs,
};

export function siteFeatureT(key: SiteFeatureI18nKey, lang: PortalUiLanguage | string | null | undefined): string {
  const dict = lang ? SITE_FEATURE_TRANSLATIONS[lang as PortalUiLanguage] : undefined;
  return dict?.[key] || SITE_FEATURE_TRANSLATIONS.en[key] || SITE_FEATURE_TRANSLATIONS.da[key] || key;
}

export function interpolateSiteFeatureLabel(
  key: SiteFeatureI18nKey,
  lang: PortalUiLanguage | string | null | undefined,
  values: Record<string, string | number>,
): string {
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value)),
    siteFeatureT(key, lang),
  );
}
